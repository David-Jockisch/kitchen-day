export function renderRecipeCard(id, doc = document) {
  const recipe = Object.hasOwn(recipeCards, id) ? recipeCards[id] : null;
  if (!recipe) return null;
  const node = (tag, text, className) => {const el = doc.createElement(tag); if(text !== undefined)el.textContent=text; if(className)el.className=className; return el;};
  const card = node('section', undefined, 'readable-recipe');
  card.append(node('p', 'Readable recipe · Preview 0.1', 'readable-label'));
  card.append(node('p', `${recipe.servings} original servings · ${recipe.portion}`, 'readable-yield'));
  card.append(node('p', 'Original recipe amounts. Quantities have not been scaled.', 'readable-caption'));
  card.append(node('h3', 'Ingredients'));
  const list = node('ul', undefined, 'readable-ingredients');
  for (const ingredient of recipe.ingredients) {
    const li = node('li');li.append(node('span',ingredient.name),node('strong',ingredient.amount));list.append(li);
  }
  card.append(list,node('h3','Preparation'));
  const steps=node('ol',undefined,'readable-steps');
  recipe.steps.forEach(step=>steps.append(node('li',step)));card.append(steps);
  if(recipe.notes.length){card.append(node('h3','Source notes'));const notes=node('ul',undefined,'readable-notes');recipe.notes.forEach(note=>notes.append(node('li',note)));card.append(notes);}
  card.append(node('p', `${recipe.collection} · ${recipe.id}. Transcribed from the original PDF. Temperature statements are from that source.`, 'readable-caption'));
  return card;
}
